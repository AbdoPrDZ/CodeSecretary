//! Generated contract files (SH-9), checked by a test so CI fails when they
//! are stale:
//!
//! - `warehouse/src/secretary_warehouse/contract/*.schema.json`: JSON Schema
//!   (2020-12) of the event envelope, the device API bodies and
//!   `AgentConfig`, for the Python services.
//! - `warehouse/src/secretary_warehouse/contract/constants.json`: event
//!   types, limits, reason/error codes and defaults, so Python never repeats
//!   them by hand.
//! - `shared/bindings/ts/contract.ts`: TypeScript types for the VS Code
//!   extension and the web app.
//!
//! Regenerate after changing a contract type:
//!
//! ```text
//! SECRETARY_BLESS=1 cargo test -p secretary-shared --features codegen generated
//! ```

use std::path::{Path, PathBuf};

use schemars::JsonSchema;
use serde_json::{Value, json};
use ts_rs::TS;

use crate::api::{self, error_code};
use crate::config::{self, AgentConfig, defaults};
use crate::event::{self, Event};
use crate::validate;

/// All generated files: (path from the repository root, contents).
pub fn files() -> Vec<(PathBuf, String)> {
    let contract = Path::new("warehouse/src/secretary_warehouse/contract");
    let mut out = vec![
        schema::<Event>(contract, "event"),
        schema::<api::BatchRequest>(contract, "batch_request"),
        schema::<api::BatchResponse>(contract, "batch_response"),
        schema::<api::AuthConfig>(contract, "auth_config"),
        schema::<api::RegisterDevice>(contract, "register_device"),
        schema::<api::DeviceRegistered>(contract, "device_registered"),
        schema::<api::Heartbeat>(contract, "heartbeat"),
        schema::<api::HeartbeatResponse>(contract, "heartbeat_response"),
        schema::<api::ApiError>(contract, "api_error"),
        schema::<AgentConfig>(contract, "agent_config"),
    ];
    out.push((contract.join("constants.json"), pretty(&constants())));
    out.push((
        PathBuf::from("shared/bindings/ts/contract.ts"),
        typescript(),
    ));
    out
}

fn schema<T: JsonSchema>(dir: &Path, name: &str) -> (PathBuf, String) {
    let schema = schemars::schema_for!(T);
    (
        dir.join(format!("{name}.schema.json")),
        pretty(&serde_json::to_value(schema).expect("schema serializes")),
    )
}

fn pretty(value: &Value) -> String {
    let mut text = serde_json::to_string_pretty(value).expect("json serializes");
    text.push('\n');
    text
}

fn secs(d: std::time::Duration) -> u64 {
    d.as_secs()
}

fn constants() -> Value {
    let interval_types: Vec<&str> = event::EVENT_TYPES
        .iter()
        .copied()
        .filter(|t| validate::is_interval(t))
        .collect();
    json!({
        "_comment": "Generated by shared/src/codegen.rs (SH-9). Do not edit.",
        "schema_version": event::SCHEMA_VERSION,
        "event_types": event::EVENT_TYPES,
        "interval_types": interval_types,
        "required_fields": validate::REQUIRED_FIELDS,
        "limits": {
            "max_future_skew_secs": validate::MAX_FUTURE_SKEW.num_seconds(),
            "max_metadata_bytes": validate::MAX_METADATA_BYTES,
            "max_text": validate::MAX_TEXT,
            "max_source": validate::MAX_SOURCE,
            "max_project_hint": validate::MAX_PROJECT_HINT,
            "max_batch_events": api::MAX_BATCH_EVENTS,
            "max_batch_bytes": api::MAX_BATCH_BYTES,
        },
        "reason_codes": [
            validate::Invalid::NotAnObject.code(),
            validate::Invalid::MissingField.code(),
            validate::Invalid::InvalidEventId.code(),
            validate::Invalid::UnsupportedSchemaVersion.code(),
            validate::Invalid::UnknownEventType.code(),
            validate::Invalid::InvalidSource.code(),
            validate::Invalid::InvalidTimestamps.code(),
            validate::Invalid::TimestampInFuture.code(),
            validate::Invalid::InvalidMetadata.code(),
            validate::Invalid::MetadataTooLarge.code(),
            validate::Invalid::InvalidField.code(),
        ],
        "error_codes": [
            error_code::INVALID_TOKEN,
            error_code::DEVICE_REVOKED,
            error_code::DEVICE_NOT_REGISTERED,
            error_code::BATCH_TOO_LARGE,
            error_code::INVALID_BODY,
        ],
        "redaction_version": config::REDACTION_VERSION,
        "agent_config_defaults": AgentConfig::default(),
        "engine_defaults": {
            "idle_threshold_secs": secs(defaults::IDLE_THRESHOLD),
            "merge_gap_secs": secs(defaults::MERGE_GAP),
            "min_session_secs": secs(defaults::MIN_SESSION),
            "context_window_secs": secs(defaults::CONTEXT_WINDOW),
            "review_confidence": defaults::REVIEW_CONFIDENCE,
            "engine_debounce_secs": secs(defaults::ENGINE_DEBOUNCE),
            "raw_retention_months": defaults::RAW_RETENTION_MONTHS,
            "ai_enabled": defaults::AI_ENABLED,
        },
    })
}

macro_rules! decls {
    ($($t:ty),* $(,)?) => {
        vec![$(format!("export {}", <$t as TS>::decl())),*]
    };
}

fn typescript() -> String {
    use crate::event::*;
    let decls: Vec<String> = decls![
        crate::ids::EventId,
        Source,
        RepositoryRef,
        Event,
        Payload,
        Empty,
        WindowFocus,
        EditorWorkspaceOpen,
        EditorFileFocus,
        EditorEditBurst,
        EditorSave,
        EditorDebugSession,
        GitCommit,
        GitCheckout,
        GitMerge,
        GitBackfillCommit,
        AgentHeartbeat,
        PauseReason,
        AgentPauseChange,
        AgentBufferOverflow,
        api::AuthConfig,
        api::RegisterDevice,
        api::DeviceRegistered,
        api::BatchRequest,
        api::BatchResponse,
        api::Rejection,
        api::Heartbeat,
        api::HeartbeatResponse,
        api::ApiError,
        AgentConfig,
        config::Exclusions,
        config::PauseWindow,
    ];
    let types = serde_json::to_string(event::EVENT_TYPES).expect("json");
    format!(
        "// Generated by shared/src/codegen.rs (SH-9). Do not edit.\n\
         // Regenerate: SECRETARY_BLESS=1 cargo test -p secretary-shared --features codegen generated\n\n\
         export const SCHEMA_VERSION = {} as const;\n\
         export const EVENT_TYPES = {types} as const;\n\
         export type EventType = (typeof EVENT_TYPES)[number];\n\n{}\n",
        event::SCHEMA_VERSION,
        decls.join("\n\n"),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .expect("shared/ has a parent")
            .to_owned()
    }

    #[test]
    fn generated_files_are_current() {
        let root = repo_root();
        let bless = std::env::var_os("SECRETARY_BLESS").is_some();
        let mut stale = Vec::new();
        for (path, expected) in files() {
            let full = root.join(&path);
            let current = std::fs::read_to_string(&full)
                .unwrap_or_default()
                .replace("\r\n", "\n");
            if current == expected {
                continue;
            }
            if bless {
                std::fs::create_dir_all(full.parent().unwrap()).unwrap();
                std::fs::write(&full, &expected).unwrap();
            } else {
                stale.push(path.display().to_string());
            }
        }
        assert!(
            stale.is_empty(),
            "generated contract files are stale: {stale:?}\n\
             run: SECRETARY_BLESS=1 cargo test -p secretary-shared --features codegen generated"
        );
    }

    #[test]
    fn event_schema_accepts_real_events_and_names_every_type() {
        let schema = serde_json::to_string(&schemars::schema_for!(Event)).unwrap();
        for event_type in event::EVENT_TYPES {
            assert!(
                schema.contains(event_type),
                "{event_type} missing from the schema"
            );
        }
    }
}
